package com.yan.backend.service;

import com.yan.backend.dto.DashboardDigestVO;

/**
 * 首页的 AI 摘要卡片。
 *
 * <h3>为什么是"读缓存"而不是"按需生成"</h3>
 *
 * <p>首页是所有人登录后的落地页。如果摘要做成"打开页面就调一次模型"，
 * 那么每个人每次进首页都要等模型 —— 本机小模型在 CPU 上跑一段话要几十秒，
 * 首页会变成整个系统里最慢的一页。所以生成是**定时 + 手动触发**的独立动作，
 * 页面这边只读一份现成的结果。
 *
 * <h3>为什么结果只放内存，不落库</h3>
 *
 * <p>它是**派生数据**，而且随每一次设备变动立刻过期。落库要面对
 * "什么时候失效""谁来清"这一串问题，而漏更新的后果是看板上挂着一份
 * 和事实不符的判断，且**不报错** —— 这比"重启后要重新生成一次"糟糕得多。
 * 这和设备健康分不落表是同一个立场。
 *
 * <p>代价是每次重启都要重跑一次。所以实现了启动预热（见
 * {@code DashboardDigestScheduler}），让用户感知不到这个空窗。
 */
public interface DashboardDigestService {

    /**
     * 取当前这份摘要。
     *
     * <p><b>只读，绝不触发生成</b> —— 它会被每次首页请求调用。
     */
    DashboardDigestVO current();

    /**
     * 请求生成一份新的摘要。
     *
     * <p>**立即返回**：真正的模型调用在后台线程上跑。返回 false 表示这次没启动，
     * 原因有三种，都会记日志：功能被关掉了、距上次不足最小间隔、
     * 上一次还在生成中。三种都不是错误，调用方不需要因此报错。
     *
     * @return 是否真的启动了这次生成
     */
    boolean requestGenerate();
}
